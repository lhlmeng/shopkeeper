"""Project entry point."""

from knowledge.app import app
from knowledge.core.config import get_settings

__all__ = ["app"]


if __name__ == "__main__":
    import uvicorn

    settings = get_settings()
    uvicorn.run(
        "main:app",
        host=settings.app_host,
        port=settings.app_port,
        reload=settings.app_env == "development",
    )
